let vogal = prompt("Digite uma vogal.").toUpperCase();
switch (vogal) {
    case "A":
        console.log("A = Apple.")
    break;
    case "E":
        console.log("E = Elephant.")
    break;
    case "I":
        console.log("I = Ice cream.")
    break;
    case "O":
        console.log("O = Orange.")
    break;
    case "U":
        console.log("U = Umbrella.")
    break;
    default:
        console.log("Não é vogal")
    break;
}