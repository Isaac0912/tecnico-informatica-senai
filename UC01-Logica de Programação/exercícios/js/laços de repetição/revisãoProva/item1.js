// reúne os relatórios das campanhas de marketing da empresa.
// Durante uma promoção, a equipe acompanha cada dia do período 
// para registrar metas e comparar os resultados diários.
// Na campanha atual, que ocorre do dia 1 ao dia 15 do mês, 
// o sistema deve gerar no console a numeração sequencial desses dias, 
// que servirá de base para o relatório de acompanhamento.

// **Comando:** Implemente em JavaScript um programa que exiba no console 
// os números inteiros de 1 a 15, um por linha, utilizando console.log().

for (let dia = 1; dia <= 15; dia++) {
    console.log(dia);
}