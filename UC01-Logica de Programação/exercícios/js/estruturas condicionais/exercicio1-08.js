// 8. Peça um número de 1 a 12 e mostre o nome do mês correspondente.
let number = Number(prompt("digite o número de um mês (1 a 12) "));

if (number === 1) {
    console.log("Janeiro.");
} else if (number === 2) {
    console.log("Fevereiro.");
} else if (number === 3) {
    console.log("Março.");
} else if (number === 4) {
    console.log ("Abril.");
} else if (number === 5) {
    console.log("Maio.");
} else if (number === 6) {
    console.log("Junho.");
} else if (number === 7) {
    console.log("Julho.");
} else if (number === 8) {
    console.log("Agosto.");
} else if (number === 9) {
    console.log("Setembro.");
} else if (number === 10) {
    console.log("Outubro.");
} else if (number === 11) {
    console.log("Novembro.");
} else if (number === 12) {
    console.log("Dezembro.");
} else {
    console.log("Entrada inválida.");
}