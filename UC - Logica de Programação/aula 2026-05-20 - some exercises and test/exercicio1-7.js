let number = Number(prompt("Digite um número de 1 a 7. "));
if (number === 1) {
    console.log("Domingo.");
} else if (number === 2) {
    console.log("Segunda.");
} else if (number === 3) {
    console.log("Terça.");
} else if (number === 4) {
    console.log("Quarta.");
} else if (number === 5) {
    console.log("Quinta.");
} else if (number === 6) {
    console.log('Sexta.');
} else if (number === 7) {
    console.log('sábado.');
} else {
    console.log("Entrada inválida.");
}