//OPERADORES DE COMPARAÇÃO
// IGUAL (==): Verificar se o valor é igual
console.log('10' == 10); // TRUE
console.log(10 == 10); // TRUE

// ESTRITAMENTE IGUAL (===): Verificar se o 
//tipo e o valor são iguais
console.log('10' === 10); // FALSE
console.log(10 === 10); // TRUE

// Diferente (!=) Verificar se o valor é diferente
console.log('11' != 10); // TRUE
console.log(11 != 10); // TRUE

// ESTRITAMENTE DIFERENTE (!==): Verificar se o 
//tipo e o valor são diferentes
console.log('11' !== 10); // TRUE
console.log(11 !== 10); // TRUE