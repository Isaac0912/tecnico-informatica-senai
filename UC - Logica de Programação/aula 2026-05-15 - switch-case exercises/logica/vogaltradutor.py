vogal = str(input("Digite uma vogal: "))

if vogal == "A":
    print("A = Apple.")
elif vogal == "E":
    print("E = Elephant.")
elif vogal == "I":
    print("I = Ice cream.")
elif vogal == "O":
    print("O = Orange.")
elif vogal == "U":
    print("U = Umbrella.")
else:
    print("Entrada inválida: você experimentou digitar apenas uma letra ou vogal?")